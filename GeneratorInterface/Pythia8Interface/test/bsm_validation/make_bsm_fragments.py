#!/usr/bin/env python3
"""Generate eta/eta' -> 2mu+A(->2e) [and -> 2pi+A(->2mu)] GEN fragments across
a grid of A masses and lifetimes, for both the dark-photon and ALP hypotheses
-- see GeneratorInterface/Pythia8Interface/interface/EtaBSMDalitz.h and
EtaBSMPiPiA.h for the physics.

Each (parent, channel, model, mass, ctau) point gets its own fragment, named
<Parent>_<channel>_<model>_mA<mass_MeV>MeV_ctau<ctau_mm>mm.py, written under
--outdir (default: Configuration/GenProduction/python/bsm/ next to this
package). PDG ids are fixed per (channel, model) pair so all fragments from
one combination share a particle definition (999001 = dark photon, 999002 =
ALP, in 2muA; 999011/999012 in 2piA, to keep the two channels' A's visibly
distinct if both are ever run in the same CMSSW job).

Mass windows (2-body kinematics, parent -> X + A with X = mu mu or pi pi,
A -> the other lepton pair; a MARGIN is subtracted from each edge because
the generator's rejection bound -> 0 there, making generation inefficient
right at threshold -- see run_and_compare.py's own edge-approach check):
  eta  -> mu mu A, A -> e e   : 2*m_e      .. M_eta  - 2*m_mu   (~0.001-0.337 GeV)
  eta' -> mu mu A, A -> e e   : 2*m_e      .. M_eta' - 2*m_mu   (~0.001-0.746 GeV)
  eta  -> pi pi A, A -> mu mu : 2*m_mu     .. M_eta  - 2*m_pi   (~0.211-0.269 GeV)
  eta' -> pi pi A, A -> mu mu : 2*m_mu     .. M_eta' - 2*m_pi   (~0.211-0.679 GeV)

Usage:
  ./make_bsm_fragments.py --channel 2muA --parent Eta EtaPrime \
      --model darkphoton alp --n-mass 8 --ctau 0 10 100 \
      --outdir /path/to/Configuration/GenProduction/python/bsm
"""
import argparse
import os

ME, MMU, MPI = 0.000511, 0.105658, 0.13957
MASS = {"Eta": 0.547862, "EtaPrime": 0.95778}
PDG = {"Eta": 221, "EtaPrime": 331}

# (channel, model) -> PDG id for A. One id per (channel, model) so every
# fragment from that combination shares a single, consistent particle
# definition; channels get disjoint id ranges so both could run in one job.
A_ID = {
    ("2muA", "darkphoton"): 999001,
    ("2muA", "alp"): 999002,
    ("2piA", "darkphoton"): 999011,
    ("2piA", "alp"): 999012,
}
A_SPIN = {"darkphoton": 3, "alp": 1}  # Pythia spinType: 3 = vector, 1 = pseudoscalar

CHANNEL_INFO = {
    # mode, recoil daughter pdgs, recoil mass, A's own decay products, window(mParent)
    "2muA": {
        "mode": "2muA",
        "recoil_ids": (13, -13),
        "recoil_mass": MMU,
        "a_decay_ids": (11, -11),
        "window": lambda mParent: (2 * ME, mParent - 2 * MMU),
    },
    "2piA": {
        "mode": "2piA",
        "recoil_ids": (211, -211),
        "recoil_mass": MPI,
        "a_decay_ids": (13, -13),
        "window": lambda mParent: (2 * MMU, mParent - 2 * MPI),
    },
}

TEMPLATE = '''import FWCore.ParameterSet.Config as cms

from Configuration.Generator.Pythia8CommonSettings_cfi import *
from Configuration.Generator.MCTunesRun3ECM13p6TeV.PythiaCP5Settings_cfi import *

# ============================================================
# ###PARENT_NAME### -> ###RECOIL_LABEL### A, A -> ###A_DECAY_LABEL###
# A = ###MODEL### (PDG id ###A_ID###, m_A = ###MASS_MEV### MeV, tau0 = ###CTAU_MM### mm)
#
# Generated by make_bsm_fragments.py -- see
# GeneratorInterface/Pythia8Interface/interface/###AMPLITUDE_HEADER###
# for the production amplitude and its documented approximations.
# Requires a CMSSW area with EtaDecayer's Pluto:mode = ###MODE### support
# built in (see GeneratorInterface/Pythia8Interface/src/EtaDecayer.cc).
# ============================================================

_generator = cms.EDFilter(
    "Pythia8GeneratorFilter",

    pythiaPylistVerbosity = cms.untracked.int32(0),
    pythiaHepMCVerbosity = cms.untracked.bool(False),
    comEnergy = cms.double(13600.0),
    maxEventsToPrint = cms.untracked.int32(0),

    PythiaParameters = cms.PSet(

        pythia8CommonSettingsBlock,
        pythia8CP5SettingsBlock,

        processParameters = cms.vstring(
            'SoftQCD:nonDiffractive = on',

            'SLHA:allowUserOverride = on',
            '###A_ID###:all = A_###CHANNEL###_###MODEL### void ###SPIN### 0 0 ###MASS_GEV### 0.0 0. 0. ###CTAU_MM###',
            '###A_ID###:isResonance = off',
            '###A_ID###:mayDecay = on',
            '###A_ID###:onMode = off',
            '###A_ID###:addChannel = 1 1.0 0 ###A_DECAY_IDS###',

            'Pluto:filter = on',
            'Pluto:allowForcedDecay = on',
            'Pluto:parent = ###PARENT_ID###',
            'Pluto:mode = ###MODE###',
            'Pluto:model = pointlike',
            'Pluto:A_id = ###A_ID###',
            'Pluto:A_type = ###MODEL###',
        ),

        parameterSets = cms.vstring(
            'pythia8CommonSettings',
            'pythia8CP5Settings',
            'processParameters'
        )
    )
)

parentfilter = cms.EDFilter(
    "PythiaFilter",
    ParticleID = cms.untracked.int32(###PARENT_ID###),
    MinEta = cms.untracked.double(-3.0),
    MaxEta = cms.untracked.double(3.0)
)
###FILTER_DEFS###
from GeneratorInterface.Core.ExternalGeneratorFilter import ExternalGeneratorFilter
generator = ExternalGeneratorFilter(_generator)

ProductionFilterSequence = cms.Sequence(
    generator *
    parentfilter###FILTER_SEQ###
)
'''

# Optional gen-level acceptance filter, mirroring the SM Eta/EtaPrime_2mu2pi fragments'
# decayfilter + mufilter_leading/subleading (same pt/eta thresholds): adapted for the
# A-mediated topology, where the leptons are A's own daughters (MotherID = A's pdg id,
# not the parent's), not direct daughters of the parent meson. Cuts the recoil pair
# (e.g. pi+pi-) at the parent-daughter level and the A->l+l- pair at the A-daughter
# level; A itself gets no cut (MinPt=0, |eta|<10 -- effectively unconstrained) since it
# is listed only because PythiaDauVFilter requires the full, exact daughter list.
FILTER_DEFS = '''
# ============================================================
# Daughter acceptance: ###PARENT_NAME### -> ###RECOIL_LABEL### A, A -> ###A_DECAY_LABEL###
# Mirrors the SM Eta_2mu2pi gen filter (same pt/eta thresholds); see make_bsm_fragments.py.
# ============================================================

decayfilter = cms.EDFilter(
    "PythiaDauVFilter",
    verbose = cms.untracked.int32(0),
    NumberDaughters = cms.untracked.int32(3),
    ParticleID = cms.untracked.int32(###PARENT_ID###),
    DaughterIDs = cms.untracked.vint32(###RECOIL_ID0###, ###RECOIL_ID1###, ###A_ID###),
    MinPt = cms.untracked.vdouble(1.0, 1.0, 0.0),
    MinEta = cms.untracked.vdouble(-2.5, -2.5, -10.0),
    MaxEta = cms.untracked.vdouble(2.5, 2.5, 10.0)
)

mufilter_leading = cms.EDFilter(
    "MCMultiParticleFilter",
    ParticleID = cms.vint32(###LEP_ID###),
    MotherID = cms.untracked.vint32(###A_ID###),
    MaxDecayRadius = cms.untracked.vdouble(2000.0),
    MaxDecayZ = cms.untracked.vdouble(4000.0),
    MinDecayZ = cms.untracked.vdouble(-4000.0),
    EtaMax = cms.vdouble(2.6),
    EtaMin = cms.vdouble(-2.6),
    PtMin = cms.vdouble(3.5),
    Status = cms.vint32(1),
    NumRequired = cms.int32(1),
    AcceptMore = cms.bool(True)
)

mufilter_subleading = cms.EDFilter(
    "MCMultiParticleFilter",
    ParticleID = cms.vint32(###LEP_ID###),
    MotherID = cms.untracked.vint32(###A_ID###),
    MaxDecayRadius = cms.untracked.vdouble(2000.0),
    MaxDecayZ = cms.untracked.vdouble(4000.0),
    MinDecayZ = cms.untracked.vdouble(-4000.0),
    EtaMax = cms.vdouble(2.6),
    EtaMin = cms.vdouble(-2.6),
    PtMin = cms.vdouble(2.5),
    Status = cms.vint32(1),
    NumRequired = cms.int32(2),
    AcceptMore = cms.bool(True)
)
'''
FILTER_SEQ = ''' *
    decayfilter *
    mufilter_leading *
    mufilter_subleading'''


def mass_grid(lo, hi, n, margin_frac=0.02):
    """n masses spanning (lo, hi), pulled in by margin_frac of the window width at
    each edge (the rejection bound -> 0 exactly at the edges, see module docstring)."""
    width = hi - lo
    lo2, hi2 = lo + margin_frac * width, hi - margin_frac * width
    if n == 1:
        return [0.5 * (lo2 + hi2)]
    return [lo2 + (hi2 - lo2) * i / (n - 1) for i in range(n)]


def write_fragment(path, parent, channel, model, mass, ctau, gen_filter=False):
    info = CHANNEL_INFO[channel]
    recoil_label = {"2muA": "mu+ mu-", "2piA": "pi+ pi-"}[channel]
    a_decay_label = {"darkphoton": {"2muA": "e+ e-", "2piA": "mu+ mu-"}, "alp": {"2muA": "e+ e-", "2piA": "mu+ mu-"}}[
        model
    ][channel]
    amplitude_header = {"2muA": "EtaBSMDalitz.h", "2piA": "EtaBSMPiPiA.h"}[channel]
    a_id = A_ID[(channel, model)]
    text = TEMPLATE
    for key, val in {
        "PARENT_NAME": parent,
        "RECOIL_LABEL": recoil_label,
        "A_DECAY_LABEL": a_decay_label,
        "MODEL": model,
        "A_ID": str(a_id),
        "MASS_MEV": "%.1f" % (mass * 1000),
        "MASS_GEV": "%.6f" % mass,
        "CTAU_MM": "%.6g" % ctau,
        "AMPLITUDE_HEADER": amplitude_header,
        "MODE": info["mode"],
        "SPIN": str(A_SPIN[model]),
        "CHANNEL": channel,
        "A_DECAY_IDS": " ".join(str(i) for i in info["a_decay_ids"]),
        "PARENT_ID": str(PDG[parent]),
        "FILTER_SEQ": FILTER_SEQ if gen_filter else "",
    }.items():
        text = text.replace("###" + key + "###", val)
    if gen_filter:
        filter_defs = FILTER_DEFS
        for key, val in {
            "PARENT_NAME": parent,
            "RECOIL_LABEL": recoil_label,
            "A_DECAY_LABEL": a_decay_label,
            "PARENT_ID": str(PDG[parent]),
            "RECOIL_ID0": str(info["recoil_ids"][0]),
            "RECOIL_ID1": str(info["recoil_ids"][1]),
            "A_ID": str(a_id),
            "LEP_ID": str(abs(info["a_decay_ids"][0])),
        }.items():
            filter_defs = filter_defs.replace("###" + key + "###", val)
        assert "###" not in filter_defs, "unreplaced placeholder in filter block for " + path
        text = text.replace("###FILTER_DEFS###", filter_defs)
    else:
        text = text.replace("###FILTER_DEFS###", "")
    assert "###" not in text, "unreplaced placeholder in " + path
    with open(path, "w") as f:
        f.write(text)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--channel", nargs="+", default=["2muA"], choices=["2muA", "2piA"])
    ap.add_argument("--parent", nargs="+", default=["Eta", "EtaPrime"], choices=["Eta", "EtaPrime"])
    ap.add_argument("--model", nargs="+", default=["darkphoton", "alp"], choices=["darkphoton", "alp"])
    ap.add_argument("--n-mass", type=int, default=8, help="number of mass grid points per (parent, channel)")
    ap.add_argument("--ctau", type=float, nargs="+", default=[0.0], help="lifetimes (mm) to scan, e.g. 0 1 10 100")
    ap.add_argument("--outdir", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "fragments"))
    ap.add_argument("--gen-filter", action="store_true",
                     help="add the SM Eta_2mu2pi-style decayfilter+mufilter_leading/subleading gen-level "
                          "acceptance chain (MotherID set to A's pdg id, since the leptons are A's daughters)")
    args = ap.parse_args()

    os.makedirs(args.outdir, exist_ok=True)
    written = []
    for channel in args.channel:
        info = CHANNEL_INFO[channel]
        for parent in args.parent:
            lo, hi = info["window"](MASS[parent])
            masses = mass_grid(lo, hi, args.n_mass)
            for model in args.model:
                for mass in masses:
                    for ctau in args.ctau:
                        name = "%s_%s_%s_mA%04dMeV_ctau%gmm.py" % (
                            parent,
                            channel,
                            model,
                            round(mass * 1000),
                            ctau,
                        )
                        path = os.path.join(args.outdir, name)
                        write_fragment(path, parent, channel, model, mass, ctau, gen_filter=args.gen_filter)
                        written.append(path)
    print("wrote %d fragments to %s" % (len(written), args.outdir))
    for p in written[:5]:
        print("  ", os.path.basename(p))
    if len(written) > 5:
        print("  ... and %d more" % (len(written) - 5))


if __name__ == "__main__":
    main()
